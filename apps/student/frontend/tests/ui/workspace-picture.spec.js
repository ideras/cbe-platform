test('a file made again in the terminal is drawn again, and one caught half written is a notice, never an error', async ({ page }) => {
  const problems = await start(page);
  await open(page, 'automaton.svg');
  const picture = pictureOf(page, 'automaton.svg');
  await expect(picture).toBeVisible();
  const first = (await measure(picture)).natural;
  await page.evaluate(() => { document.querySelector('img[alt="Picture drawn by automaton.svg"]').__drawn = true; });

  // dot writes it again: the picture follows, in the same place, without opening the file again.
  await write(page, 'automaton.svg', redrawn);
  await expect.poll(async () => (await measure(picture)).natural).toBeGreaterThan(first * 1.8);
  expect(await drawnText(picture)).toBe(redrawn);
  expect(await page.evaluate(() => document.querySelector('img[alt="Picture drawn by automaton.svg"]').__drawn)).toBe(true);
  expect(await server(page, 'server.requests.filter(r => r.type === "fs.read" && r.path === "automaton.svg").length')).toBeGreaterThan(1);

  // Caught while dot was writing it, in the middle and before the svg element: a notice, and the picture comes back with the next change.
  for (const cut of [halfWritten, barelyStarted]) {
    await write(page, 'automaton.svg', cut);
    await expect(notice(page)).toBeVisible();
    await expect(picture).toHaveCount(0);
    await expect(viewButton(page, 'Picture')).toHaveAttribute('aria-pressed', 'true');
    await write(page, 'automaton.svg', graphviz);
    await expect(picture).toBeVisible();
    await expect(notice(page)).toHaveCount(0);
    await expect.poll(async () => (await measure(picture)).natural).toBe(first);
  }

  // The notice's button shows what the file holds.
  await write(page, 'automaton.svg', halfWritten);
  await expect(notice(page)).toBeVisible();
  await page.getByRole('button', { name: 'Show the source', exact: true }).click();
  await expect(editorOf(page, 'automaton.svg')).toBeFocused();
  await expect(editorOf(page, 'automaton.svg')).toContainText('<svg width="170pt"');
  await page.waitForTimeout(300);
  expect(problems).toEqual([]);
});

