test('Fit, − and +, and 100 % size the picture, and a large one scrolls with the arrow keys', async ({ page }) => {
  await start(page);
  await open(page, 'wide.svg');
  const picture = pictureOf(page, 'wide.svg');
  const region = regionOf(page, 'wide.svg');
  const zoom = zoomGroup(page);
  await expect(picture).toBeVisible();
  // Fit: the whole width in view, smaller than its own size, nothing to scroll.
  const fit = await measure(picture);
  expect(fit.natural).toBe(3000);
  expect(fit.width).toBeLessThanOrEqual(fit.room);
  expect(fit.scrollWidth).toBeLessThanOrEqual(fit.room);
  await expect(zoom.getByRole('button', { name: 'Fit', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(zoom).toContainText(`${Math.round(fit.width / 30)} %`);

  await zoom.getByRole('button', { name: '+ Zoom in' }).click();
  expect((await measure(picture)).width).toBe(1500);
  await expect(zoom).toContainText('50 %');
  await expect(zoom.getByRole('button', { name: 'Fit', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await zoom.getByRole('button', { name: '100 % Actual size' }).click();
  const actual = await measure(picture);
  expect(actual.width).toBe(3000);
  expect(actual.scrollWidth).toBeGreaterThan(actual.room);
  await expect(zoom).toContainText('100 %');

  // The arrow keys move a picture larger than the room.
  await region.focus();
  const left = (await measure(picture)).left;
  for (let i = 0; i < 8; i += 1) await page.keyboard.press('ArrowRight');
  await expect.poll(async () => (await measure(picture)).left).toBeGreaterThan(left + 100);

  // The keys of the zoom: + − and 0, with the picture's region in focus; they type nothing anywhere.
  await page.keyboard.press('+');
  expect((await measure(picture)).width).toBe(4500);
  await page.keyboard.press('-');
  await page.keyboard.press('-');
  expect((await measure(picture)).width).toBe(2250);
  await page.keyboard.press('0');
  expect((await measure(picture)).width).toBe(fit.width);
  await expect(region).toBeFocused();

  // At the largest step + says it can go no further, and keeps the keyboard.
  const plus = zoom.getByRole('button', { name: '+ Zoom in' });
  await plus.focus();
  for (let i = 0; i < 8; i += 1) await page.keyboard.press('Enter');
  expect((await measure(picture)).width).toBe(12000);
  await expect(plus).toHaveAttribute('aria-disabled', 'true');
  await expect(plus).toBeFocused();
  await zoom.getByRole('button', { name: 'Fit', exact: true }).click();
  expect((await measure(picture)).width).toBe(fit.width);
  await expect(zoom.getByRole('button', { name: '− Zoom out' })).toHaveAttribute('aria-disabled', 'true');

  // Ctrl and the wheel zoom, as in a picture viewer, and not the window.
  const box = await region.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.keyboard.down('Control');
  await page.mouse.wheel(0, -120);
  await page.keyboard.up('Control');
  await expect.poll(async () => (await measure(picture)).width).toBe(1500);
  expect(await page.evaluate(() => window.visualViewport?.scale ?? 1)).toBe(1);
  expect(await page.evaluate(() => window.__storage)).toEqual([]);
});

