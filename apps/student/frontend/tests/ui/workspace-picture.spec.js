const tall = graphviz.replace('<g id="graph0"', `${Array.from({ length: 200 }, (_, i) => `<!-- line ${i} of the comments -->`).join('\n')}\n<g id="graph0"`);

const project = {
  'Makefile': 'all:\n\techo build\n',
  'src/main.cpp': 'int main() { return 0; }\n',
  'notes.txt': 'first line\nsecond line\n',
  'automaton.svg': graphviz,
  'wide.svg': wide,
  'tall.svg': tall,
};

async function start(page, options = {}, viewport = { width: 1280, height: 800 }) {
  await page.setViewportSize(viewport);
  const problems = [];
  page.on('pageerror', error => problems.push(`pageerror: ${error.message}`));
  page.on('console', message => { if (message.type() === 'error') problems.push(`console: ${message.text()}`); });
  await page.addInitScript(() => {
    window.__storage = [];
    for (const method of ['setItem', 'removeItem', 'clear']) {
      const original = Storage.prototype[method];
      Storage.prototype[method] = function (...args) { window.__storage.push(method); return original.apply(this, args); };
    }
  });
  await page.goto('/');
  await page.evaluate(value => window.__studentHarness.useWorkspace(value), { files: project, ...options });
  await page.getByLabel('I have read these rules').check();
  await page.getByLabel('Account number').fill('00123');
  await page.getByLabel('Exam PIN').fill('synthetic PIN');
  await page.getByRole('button', { name: 'Login / resume' }).click();
  await expect(page.getByRole('tree', { name: 'Project files' })).toBeVisible();
  await expect(page.getByRole('treeitem', { name: 'Makefile' })).toBeVisible();
  return problems;
}
const server = (page, expression, arg) => page.evaluate(([code, value]) => new Function('server', 'value', `return ${code}`)(window.__studentHarness.workspaceServer, value), [expression, arg]);
const write = (page, path, content) => server(page, 'server.externalWrite(value[0], value[1])', [path, content]);
const open = (page, name) => page.getByRole('treeitem', { name, exact: true }).click();
const pictureOf = (page, name) => page.getByRole('img', { name: `Picture drawn by ${name}` });
const regionOf = (page, name) => page.getByRole('region', { name: `Picture of ${name}` });
const editorOf = (page, name) => page.getByRole('textbox', { name: `Editor for ${name}` });
const viewButton = (page, name) => page.getByRole('button', { name, exact: true });
const zoomGroup = page => page.getByRole('group', { name: 'Picture zoom' });
const notice = page => page.getByText('This file cannot be drawn as a picture yet.');
// The picture's address, read back as the text it draws.
const drawnText = image => image.evaluate(img => decodeURIComponent(img.getAttribute('src').slice(img.getAttribute('src').indexOf(',') + 1)));
// How the picture is drawn, and the room it is in.
const measure = image => image.evaluate(img => {
  const room = img.parentElement;
  return { width: img.getBoundingClientRect().width, height: img.getBoundingClientRect().height, natural: img.naturalWidth,
    room: room.clientWidth, roomHeight: room.clientHeight, scrollWidth: room.scrollWidth, left: room.scrollLeft, top: room.scrollTop };
});

test('an SVG file opens as its picture, and Source shows its XML in the editor', async ({ page }) => {
  const problems = await start(page);
  await open(page, 'automaton.svg');
  const picture = pictureOf(page, 'automaton.svg');
  await expect(picture).toBeVisible();
  expect(await picture.evaluate(img => img.complete && img.naturalWidth > 0 && img.naturalHeight > 0)).toBe(true);
  expect(await picture.getAttribute('src')).toMatch(/^data:image\/svg\+xml/);
  expect(await drawnText(picture)).toBe(graphviz);
  expect(await picture.getAttribute('draggable')).toBe('false');
  // The picture, not the editor; the keyboard is in the picture, as it would be in the editor for any other file.
  await expect(editorOf(page, 'automaton.svg')).toBeHidden();
  await expect(regionOf(page, 'automaton.svg')).toBeFocused();
  await expect(page.getByRole('group', { name: 'Show automaton.svg as' })).toBeVisible();
  await expect(viewButton(page, 'Picture')).toHaveAttribute('aria-pressed', 'true');
  await expect(viewButton(page, 'Source')).toHaveAttribute('aria-pressed', 'false');
  // The editor's A− and A+ size the code text: a picture has its own zoom instead.
  await expect(page.getByRole('button', { name: /Larger code text/ })).toHaveCount(0);
  await expect(zoomGroup(page)).toBeVisible();

  await viewButton(page, 'Source').click();
  const editor = editorOf(page, 'automaton.svg');
  await expect(editor).toBeVisible();
  await expect(editor).toBeFocused();
  await expect(editor).toContainText('<svg width="170pt" height="52pt"');
  await expect(picture).toBeHidden();
  await expect(zoomGroup(page)).toBeHidden();
  await expect(page.getByRole('button', { name: /Larger code text/ })).toBeVisible();
  await expect(viewButton(page, 'Source')).toHaveAttribute('aria-pressed', 'true');

  await viewButton(page, 'Picture').click();
  await expect(picture).toBeVisible();
  await expect(regionOf(page, 'automaton.svg')).toBeFocused();
  await expect(editor).toBeHidden();
  // Opening it, and switching, wrote nothing.
  expect(await server(page, 'server.requests.filter(r => r.type === "fs.write").length')).toBe(0);
  await expect(page.getByRole('tab', { name: /automaton\.svg/ })).not.toContainText('●');
  expect(problems).toEqual([]);
});

test('the editor behind the picture keeps its cursor and its scroll, and each tab keeps its view', async ({ page }) => {
  await start(page);
  await open(page, 'tall.svg');
  await expect(pictureOf(page, 'tall.svg')).toBeVisible();
  await viewButton(page, 'Source').click();
  const editor = editorOf(page, 'tall.svg');
  await expect(editor).toBeFocused();
  await page.keyboard.press('Control+Home');
  for (let i = 0; i < 130; i += 1) await page.keyboard.press('ArrowDown');
  // Not on the last line in view: focusing the editor may scroll a line at the very edge fully into view (WebKit does), which is not a move.
  for (let i = 0; i < 10; i += 1) await page.keyboard.press('ArrowUp');
  const where = () => page.evaluate(() => ({ line: Number(document.querySelector('.cm-activeLineGutter')?.textContent), scroll: Math.round(document.querySelector('.cm-scroller').scrollTop) }));
  const before = await where();
  expect(before.line).toBe(121);
  expect(before.scroll).toBeGreaterThan(500);
  await viewButton(page, 'Picture').click();
  await expect(pictureOf(page, 'tall.svg')).toBeVisible();
  await viewButton(page, 'Source').click();
  await expect(editor).toBeFocused();
  expect(await where()).toEqual(before);

  // Another file and back: the SVG is still shown as its source, as the student left it, with its cursor and its scroll.
  await open(page, 'notes.txt');
  await expect(editorOf(page, 'notes.txt')).toBeVisible();
  await expect(page.getByRole('group', { name: /^Show .* as$/ })).toHaveCount(0);
  await page.getByRole('tab', { name: /tall\.svg/ }).click();
  await expect(editor).toBeVisible();
  await expect(viewButton(page, 'Source')).toHaveAttribute('aria-pressed', 'true');
  await expect(pictureOf(page, 'tall.svg')).toBeHidden();
  await expect.poll(where).toEqual(before);
  // Closed and opened again, it is a picture again.
  await page.getByRole('button', { name: 'Close tall.svg' }).click();
  await expect(page.getByRole('tab', { name: /tall\.svg/ })).toHaveCount(0);
  await open(page, 'tall.svg');
  await expect(pictureOf(page, 'tall.svg')).toBeVisible();
});

