const redrawn = graphviz.replace('width="170pt" height="52pt"', 'width="340pt" height="104pt"');
// A file read while dot was writing it: cut in the middle, and cut before the svg element.
const halfWritten = graphviz.slice(0, Math.floor(graphviz.length * 0.6));
const barelyStarted = graphviz.slice(0, 30);
// An automaton too wide for any window: thirty states in a row.
const wide = `<svg xmlns="http://www.w3.org/2000/svg" width="3000" height="300" viewBox="0 0 3000 300"><rect width="3000" height="300" fill="white"/>${
  Array.from({ length: 30 }, (_, i) => `<circle cx="${50 + i * 100}" cy="150" r="40" fill="none" stroke="black"/><text x="${50 + i * 100}" y="155" text-anchor="middle">s${i}</text>`).join('')}</svg>\n`;
