func pngBytes(t testing.TB, width, height int) []byte {
	t.Helper()
	var out bytes.Buffer
	if err := png.Encode(&out, image.NewGray(image.Rect(0, 0, width, height))); err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}

func jpegBytes(t testing.TB) []byte {
	t.Helper()
	var out bytes.Buffer
	if err := jpeg.Encode(&out, image.NewRGBA(image.Rect(0, 0, 8, 8)), nil); err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}

func gifBytes(t testing.TB) []byte {
	t.Helper()
	var out bytes.Buffer
	if err := gif.Encode(&out, image.NewPaletted(image.Rect(0, 0, 4, 4), color.Palette{color.Black, color.White}), nil); err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}

// pngHeader is a PNG that stops after its header and claims the given size: DecodeConfig reads no more, so a decompression
// bomb is cheap to write.
func pngHeader(width, height uint32) []byte {
	var out bytes.Buffer
	out.WriteString("\x89PNG\r\n\x1a\n")
	header := make([]byte, 13)
	binary.BigEndian.PutUint32(header[0:], width)
	binary.BigEndian.PutUint32(header[4:], height)
	header[8], header[9] = 8, 6 // 8 bits per channel, RGBA
	chunk := append([]byte("IHDR"), header...)
	binary.Write(&out, binary.BigEndian, uint32(len(header)))
	out.Write(chunk)
	binary.Write(&out, binary.BigEndian, crc32.ChecksumIEEE(chunk))
	return out.Bytes()
}

const plainSVG = `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><circle cx="10" cy="10" r="5" fill="#000"/></svg>`

func TestValidateAcceptsEachFormat(t *testing.T) {
	for name, test := range map[string]struct {
		data []byte
		want string
	}{
		"png":  {pngBytes(t, 16, 9), PNG},
		"jpeg": {jpegBytes(t), JPEG},
		"gif":  {gifBytes(t), GIF},
		"svg":  {[]byte(plainSVG), SVG},
		"svg with a byte order mark and blank lines": {[]byte("\xef\xbb\xbf\n\n" + plainSVG + "\n"), SVG},
	} {
		got, err := Validate(test.data)
		if err != nil || got != test.want {
			t.Errorf("%s: Validate = %q, %v; want %q", name, got, err, test.want)
		}
	}
}

func TestValidateRefusesBadRasters(t *testing.T) {
	broken := pngBytes(t, 4, 4)
	broken[0] = 0 // the signature no longer says PNG
	truncated := pngBytes(t, 4, 4)[:20]
	for name, test := range map[string]struct {
		data []byte
		want string
	}{
		"empty":                 {nil, "empty"},
		"bad signature":         {broken, "not a PNG, JPEG, GIF or SVG image"},
		"html":                  {[]byte("hello <b>world</b>"), "not a PNG, JPEG, GIF or SVG image"},
		"truncated header":      {truncated, "damaged"},
		"jpeg signature only":   {[]byte("\xff\xd8\xff"), "damaged"},
		"too wide":              {pngHeader(MaxDimension+1, 10), "each side must be between 1 and 4000"},
		"too tall":              {pngHeader(10, MaxDimension+1), "each side must be between 1 and 4000"},
		"zero width":            {pngHeader(0, 10), "damaged"},
		"too many pixels":       {pngHeader(3500, 3500), "at most 12 million pixels"},
		"larger than the limit": {append(pngBytes(t, 4, 4), make([]byte, MaxImageBytes)...), "larger than 128 KiB"},
	} {
		if mime, err := Validate(test.data); err == nil || !strings.Contains(err.Error(), test.want) {
			t.Errorf("%s: Validate = %q, %v; want an error with %q", name, mime, err, test.want)
		}
	}
	if _, err := Validate(pngHeader(MaxDimension, 3000)); err != nil {
		t.Errorf("a 4000 x 3000 image (exactly 12 million pixels) must be accepted: %v", err)
	}
}

